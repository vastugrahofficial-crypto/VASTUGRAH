export function getRudrakshaByMukhi(mukhi) {
  return RUDRAKSHA_DATA.find(r => r.mukhi === mukhi);
}

export function recommendRudraksha(moonSign) {
  if (!moonSign) return null;
  const cleanSign = moonSign.split(" ")[0].trim();
  const map = {
    Aries: 3, Taurus: 6, Gemini: 4, Cancer: 2,
    Leo: 1, Virgo: 4, Libra: 6, Scorpio: 3,
    Sagittarius: 5, Capricorn: 7, Aquarius: 7, Pisces: 5
  };
  const mukhiNum = map[cleanSign] || 5;
  const bead = RUDRAKSHA_DATA.find(r => r.mukhi === mukhiNum) || RUDRAKSHA_DATA[4];

  return {
    mukhi: `${bead.mukhi} Mukhi`,
    name: bead.name,
    deity: bead.deity,
    planet: bead.planet,
    moonSign: cleanSign,
    mantra: bead.mantra,
    benefits: bead.benefits,
    wearing: bead.howToWear,
    puja: bead.puja,
    caution: bead.caution
  };
}

